function buildSearchTermFrequencies(content, title) {
  const terms = new Map();
  addTerms(terms, tokenizeSearchText(stripWikiSyntaxForSearch(content)), 1);

  if (title) {
    addTerms(terms, tokenizeSearchText(title), 3);
  }

  return terms;
}

function tokenizeSearchText(text) {
  return (text.toLowerCase().normalize("NFKD").match(TERM_PATTERN) ?? []).filter(
    (term) => !STOP_WORDS.has(term)
  );
}

function stripWikiSyntaxForSearch(content) {
  return content
    .replace(/^={2,6}\s*(.*?)\s*={2,6}$/gm, "$1")
    .replace(/\[\[[^\]|]+?\|([^\]]+?)\]\]/g, "$1")
    .replace(/\[\[([^\]]+?)\]\]/g, "$1")
    .replace(/\{\{[^|}]+?\|([^}]+?)\}\}/g, "$1")
    .replace(/\{\{([^}]+?)\}\}/g, "$1")
    .replace(/<code[\s\S]*?<\/code>/gi, " ")
    .replace(/<file[\s\S]*?<\/file>/gi, " ")
    .replace(/%%[\s\S]*?%%/g, " ")
    .replace(/[=*_/`~[\]{}|<>#]/g, " ");
}

function addTerms(target, terms, weight) {
  for (const term of terms) {
    target.set(term, (target.get(term) ?? 0) + weight);
  }
}

function sql(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function parseArgs(argv) {
  const args = {
    source: "../dokuwiki",
    dryRun: false,
    sqlOut: ""
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--source") {
      args.source = argv[++index];
    } else if (arg === "--dry-run") {
      args.dryRun = true;
    } else if (arg === "--sql-out") {
      args.sqlOut = argv[++index];
    }
  }

  return args;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const plan = await buildImportPlan(args.source);

  if (args.sqlOut) {
    await writePageImportSql(plan, args.sqlOut);
  }

  console.log(JSON.stringify(plan, null, 2));

  if (!args.dryRun) {
    process.exitCode = 2;
    console.error("Only --dry-run mode is implemented in the import planner so far.");
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
