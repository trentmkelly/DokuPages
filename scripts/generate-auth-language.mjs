#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..");
const DOKUWIKI_ROOT = path.resolve(REPO_ROOT, "..", "dokuwiki");
const OUTPUT = path.join(REPO_ROOT, "src", "wiki", "auth-language.ts");

const LANGUAGE_KEYS = [
  "btn_login",
  "btn_logout",
  "btn_register",
  "btn_resendpwd",
  "btn_reset",
  "btn_back",
  "user",
  "pass",
  "newpass",
  "oldpass",
  "passchk",
  "remember",
  "fullname",
  "email",
  "badlogin",
  "badpassconfirm",
  "regmissing",
  "reguexists",
  "regsuccess",
  "regsuccess2",
  "regfail",
  "regmailfail",
  "regbadmail",
  "regbadpass",
  "regpwmail",
  "reghere",
  "profchanged",
  "profdeleted",
  "pwdforget",
  "resendna",
  "resendpwd",
  "resendpwdmissing",
  "resendpwdnouser",
  "resendpwdbadauth",
  "resendpwdconfirm",
  "resendpwdsuccess",
  "lockedby",
  "lockexpire",
  "accessdenied"
];

const PAGE_KEYS = ["login", "register", "resendpwd", "resetpwd", "denied", "locked"];

async function main() {
  const languages = await supportedLanguages();
  const fallback = await languagePack("en");
  const packs = {};

  for (const language of languages) {
    const pack = await languagePack(language);
    packs[language] = diffPack(pack, fallback);
  }

  packs.en = fallback;

  await mkdir(path.dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, renderTypeScript(languages, packs), "utf8");
}

async function supportedLanguages() {
  const source = await readFile(path.join(REPO_ROOT, "src", "wiki", "language.ts"), "utf8");
  const match = source.match(/SUPPORTED_LANGUAGES\s*=\s*\[([\s\S]*?)\]\s*as const/);
  if (!match) throw new Error("Unable to read SUPPORTED_LANGUAGES.");
  return [...match[1].matchAll(/"([^"]+)"/g)].map((item) => item[1]);
}

async function languagePack(language) {
  const langPhp = await readOptional(path.join(DOKUWIKI_ROOT, "inc", "lang", language, "lang.php"));
  const strings = parseLangPhp(langPhp);
  const pages = {};

  for (const page of PAGE_KEYS) {
    const value = await readOptional(
      path.join(DOKUWIKI_ROOT, "inc", "lang", language, `${page}.txt`)
    );
    if (value) pages[page] = value.trim();
  }

  return {
    strings: Object.fromEntries(
      LANGUAGE_KEYS.filter((key) => strings[key] !== undefined).map((key) => [key, strings[key]])
    ),
    pages
  };
}

async function readOptional(file) {
  try {
    return await readFile(file, "utf8");
  } catch (error) {
    if (error && error.code === "ENOENT") return "";
    throw error;
  }
}

function parseLangPhp(source) {
  const values = {};
  const pattern = /\$lang\[['"]([^'"]+)['"]\]\s*=\s*('(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*")\s*;/g;

  for (const match of source.matchAll(pattern)) {
    values[match[1]] = decodePhpString(match[2]);
  }

  return values;
}

function decodePhpString(value) {
  const quote = value[0];
  const body = value.slice(1, -1);

  if (quote === "'") {
    return body.replace(/\\\\/g, "\\").replace(/\\'/g, "'");
  }

  return body.replace(/\\([nrt"\\$])/g, (_, escaped) => {
    switch (escaped) {
      case "n":
        return "\n";
      case "r":
        return "\r";
      case "t":
        return "\t";
      default:
        return escaped;
    }
  });
}

function diffPack(pack, fallback) {
  return {
    strings: Object.fromEntries(
      Object.entries(pack.strings).filter(([key, value]) => fallback.strings[key] !== value)
    ),
    pages: Object.fromEntries(
      Object.entries(pack.pages).filter(([key, value]) => fallback.pages[key] !== value)
    )
  };
}

function renderTypeScript(languages, packs) {
  return `// Generated by scripts/generate-auth-language.mjs from DokuWiki inc/lang/*.
// DokuWiki language packs are GPL-2.0 licensed.

export const AUTH_LANGUAGE_KEYS = ${JSON.stringify(LANGUAGE_KEYS, null, 2)} as const;
export type AuthLanguageKey = (typeof AUTH_LANGUAGE_KEYS)[number];

export const AUTH_PAGE_KEYS = ${JSON.stringify(PAGE_KEYS, null, 2)} as const;
export type AuthPageKey = (typeof AUTH_PAGE_KEYS)[number];

interface AuthLanguagePack {
  strings: Partial<Record<AuthLanguageKey, string>>;
  pages: Partial<Record<AuthPageKey, string>>;
}

export const AUTH_LANGUAGE_PACKS = ${JSON.stringify(packs, null, 2)} as const satisfies Record<string, AuthLanguagePack>;

const DEFAULT_LANGUAGE = "en";
const AUTH_LANGUAGE_PACK_MAP: Record<string, AuthLanguagePack> = AUTH_LANGUAGE_PACKS;

export function authLang(language: string, key: AuthLanguageKey): string {
  return lookupAuthValue(language, "strings", key);
}

export function authPageText(language: string, key: AuthPageKey): string {
  return lookupAuthValue(language, "pages", key);
}

export function authPageTitle(language: string, key: AuthPageKey): string {
  const text = authPageText(language, key);
  return text.match(/^={2,}\\s*(.*?)\\s*=+\\s*$/m)?.[1] ?? authLang(language, pageTitleButtonKey(key));
}

function lookupAuthValue<
  Section extends keyof AuthLanguagePack,
  Key extends keyof AuthLanguagePack[Section]
>(language: string, section: Section, key: Key): string {
  for (const candidate of languageCandidates(language)) {
    const value = AUTH_LANGUAGE_PACK_MAP[candidate]?.[section]?.[key];
    if (typeof value === "string") return value;
  }
  return "";
}

function languageCandidates(language: string): string[] {
  const normalized = normalizeLanguage(language);
  const base = normalized.split("-")[0] || DEFAULT_LANGUAGE;
  return [...new Set([normalized, base, DEFAULT_LANGUAGE])];
}

function normalizeLanguage(language: string): string {
  return language
    .trim()
    .toLowerCase()
    .replaceAll("_", "-")
    .replace(/[^a-z0-9-]+/g, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

function pageTitleButtonKey(key: AuthPageKey): AuthLanguageKey {
  switch (key) {
    case "login":
      return "btn_login";
    case "register":
      return "btn_register";
    case "resendpwd":
    case "resetpwd":
      return "btn_resendpwd";
    case "denied":
      return "accessdenied";
    case "locked":
      return "lockedby";
  }
}
`;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
